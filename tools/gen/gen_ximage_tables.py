#!/usr/bin/env python3
"""Extract ximage.dll's pixel-format tables into a C source file.

- .data 06f84150: 22 dwords, pixel-format index -> D3DFORMAT / FourCC
  (searched by 06f82900).
- .data 06f841a8: 15 descriptors of 0x4c bytes (19 dwords), indexed by
  06f82920; +4 is bits per pixel.

Usage: gen_ximage_tables.py game/EXE/ximage.dll src/dalibs/ximage/xi_tables.c
"""
import struct
import sys

IMAGE_BASE = 0x06f80000
D3DFMT_VA = 0x06f84150
D3DFMT_COUNT = 22
DESC_VA = 0x06f841a8
DESC_COUNT = 15
DESC_WORDS = 0x4c // 4


def va_to_off(pe, va):
    pe_off = struct.unpack_from("<I", pe, 0x3c)[0]
    nsec = struct.unpack_from("<H", pe, pe_off + 6)[0]
    opt_size = struct.unpack_from("<H", pe, pe_off + 20)[0]
    sec = pe_off + 24 + opt_size
    rva = va - IMAGE_BASE
    for i in range(nsec):
        vsize, vaddr, rsize, roff = struct.unpack_from("<IIII", pe, sec + 40 * i + 8)
        if vaddr <= rva < vaddr + max(vsize, rsize):
            return rva - vaddr + roff
    raise ValueError("VA %#x not in any section" % va)


def dwords(pe, va, n):
    return struct.unpack_from("<%dI" % n, pe, va_to_off(pe, va))


def main():
    pe = open(sys.argv[1], "rb").read()
    fmts = dwords(pe, D3DFMT_VA, D3DFMT_COUNT)
    descs = dwords(pe, DESC_VA, DESC_COUNT * DESC_WORDS)
    out = ["/* xi_tables.c — GENERATED by tools/gen/gen_ximage_tables.py from",
           " * game/EXE/ximage.dll. Do not edit. */",
           '#include "xi_internal.h"',
           "",
           "/* orig: .data 06f84150 — pixel-format index -> D3DFORMAT or FourCC. */",
           "const uint32_t xi_pf_d3dfmt[XI_PF_D3DFMT_COUNT] = {"]
    for i in range(0, D3DFMT_COUNT, 6):
        out.append("    " + " ".join("0x%08x," % v for v in fmts[i:i + 6]))
    out += ["};",
            "",
            "/* orig: .data 06f841a8 — pixel-format descriptors, 0x4c bytes each. */",
            "const uint32_t xi_pf_desc[XI_PF_DESC_COUNT][XI_PF_DESC_WORDS] = {"]
    for d in range(DESC_COUNT):
        row = descs[d * DESC_WORDS:(d + 1) * DESC_WORDS]
        out.append("    { " + ", ".join("0x%x" % v for v in row) + " },")
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
