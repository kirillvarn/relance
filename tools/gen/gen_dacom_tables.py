#!/usr/bin/env python3
"""Extract the CRC table from game/EXE/dacom.dll into a C source file.

The table is not the standard 0xEDB88320 table (entry 1 is 0x09073096), so
it is copied from the original instead of computed.

Usage: gen_dacom_tables.py game/EXE/dacom.dll src/dalibs/dacom/dacom_tables.c
"""
import struct
import sys

IMAGE_BASE = 0x065b0000
CRC_TABLE_VA = 0x065b8530   # 256 dwords, used by 065b60f0 and friends


def va_to_off(pe, va):
    pe_off = struct.unpack_from("<I", pe, 0x3c)[0]
    nsec = struct.unpack_from("<H", pe, pe_off + 6)[0]
    opt_size = struct.unpack_from("<H", pe, pe_off + 20)[0]
    sec = pe_off + 24 + opt_size
    rva = va - IMAGE_BASE
    for i in range(nsec):
        vsize, vaddr, rsize, roff = struct.unpack_from("<IIII", pe, sec + 40 * i + 8)
        if vaddr <= rva < vaddr + max(vsize, rsize):
            return rva - vaddr + roff
    raise ValueError("VA %#x not in any section" % va)


def main():
    pe = open(sys.argv[1], "rb").read()
    off = va_to_off(pe, CRC_TABLE_VA)
    table = struct.unpack_from("<256I", pe, off)
    out = ["/* dacom_tables.c — GENERATED by tools/gen/gen_dacom_tables.py from",
           " * game/EXE/dacom.dll. Do not edit. */",
           '#include "dacom_internal.h"',
           "",
           "/* orig: .data 065b8530 — CRC table (non-standard variant). */",
           "const uint32_t dacom_crc_table[256] = {"]
    for i in range(0, 256, 6):
        out.append("    " + " ".join("0x%08xu," % v for v in table[i:i + 6]))
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
