#!/usr/bin/env python3
"""Extract readfile.dll's wildcard fold table into a C source file.

The table at .data 06b7a0d8 maps ASCII upper case to lower case and '\\' to
'/'. The matcher (06b761a0) indexes it with a *signed* char, so bytes
0x80..0xff read the 128 bytes in front of it (the tail of a string). The
port reproduces that by copying 384 bytes: 06b7a058..06b7a1d7.

Usage: gen_readfile_tables.py game/EXE/readfile.dll src/dalibs/readfile/rf_tables.c
"""
import struct
import sys

IMAGE_BASE = 0x06b70000
FOLD_VA = 0x06b7a0d8


def va_to_off(pe, va):
    pe_off = struct.unpack_from("<I", pe, 0x3c)[0]
    nsec = struct.unpack_from("<H", pe, pe_off + 6)[0]
    opt_size = struct.unpack_from("<H", pe, pe_off + 20)[0]
    sec = pe_off + 24 + opt_size
    rva = va - IMAGE_BASE
    for i in range(nsec):
        vsize, vaddr, rsize, roff = struct.unpack_from("<IIII", pe, sec + 40 * i + 8)
        if vaddr <= rva < vaddr + max(vsize, rsize):
            return rva - vaddr + roff
    raise ValueError("VA %#x not in any section" % va)


def main():
    pe = open(sys.argv[1], "rb").read()
    off = va_to_off(pe, FOLD_VA - 128)
    data = pe[off:off + 384]
    out = ["/* rf_tables.c — GENERATED by tools/gen/gen_readfile_tables.py from",
           " * game/EXE/readfile.dll. Do not edit. */",
           '#include "rf_internal.h"',
           "",
           "/* orig: .data 06b7a058..06b7a1d7. Index with (signed char)c + 128. */",
           "const uint8_t rf_fold_table[384] = {"]
    for i in range(0, 384, 16):
        out.append("    " + " ".join("0x%02x," % b for b in data[i:i + 16]))
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
