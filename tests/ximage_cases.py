#!/usr/bin/env python3
"""Generate tests/ximage_cases.txt: random BigImage cases (fixed seed) for
test_ximage.c. Field order is the enum in tests/test_ximage.c. Negative
numbers are written as unsigned 32-bit; floats as their IEEE bits.

usage: ximage_cases.py > tests/ximage_cases.txt
"""
import random
import struct

N_CASES = 1000
FMTS = 22           # pixel-format indices 0..21 (ximage.dll 06f84150)


def u32(v):
    return v & 0xffffffff


def fbits(f):
    return struct.unpack("<I", struct.pack("<f", f))[0]


def rand_float(rng):
    special = [0.0, 1.0, 0.5, 0.999999, 1.0000001, -0.0, -0.25, 1.5, 3.0,
               float("nan"), float("inf"), float("-inf"), 1e10, -1e10, 1e-30]
    if rng.random() < 0.3:
        return fbits(rng.choice(special))
    return fbits(rng.uniform(-0.5, 1.5))


def tile_size(rng):
    if rng.random() < 0.15:
        return rng.randint(1, 300)
    return rng.choice([8, 16, 32, 64, 100, 128, 256, 512])


def rect(rng, w, h, tw, th):
    xs = [rng.randint(-tw, w + tw) for _ in range(2)]
    ys = [rng.randint(-th, h + th) for _ in range(2)]
    if rng.random() < 0.3:          # both edges inside one tile: fractional u0..u1 / v0..v1
        tx, ty = rng.randint(0, max(0, w // tw)), rng.randint(0, max(0, h // th))
        xs = [tx * tw + rng.randint(0, tw - 1) for _ in range(2)]
        ys = [ty * th + rng.randint(0, th - 1) for _ in range(2)]
    if rng.random() < 0.3:          # usually ordered, sometimes reversed
        xs.sort(reverse=True)
    elif rng.random() < 0.9:
        xs.sort()
    if rng.random() < 0.3:
        ys.sort(reverse=True)
    elif rng.random() < 0.9:
        ys.sort()
    if rng.random() < 0.05:
        xs[1] = xs[0]               # empty
    return [xs[0], ys[0], xs[1], ys[1]]


def dst_rect(rng):
    x0, y0 = rng.randint(-500, 1500), rng.randint(-500, 1500)
    return [x0, y0, x0 + rng.randint(-300, 1200), y0 + rng.randint(-300, 1200)]


def case(rng, i):
    tw = tile_size(rng)
    th = tw if rng.random() < 0.7 else tile_size(rng)
    # images of up to ~4x4 tiles; exact multiples and empty ones on purpose
    w = rng.choice([0, tw, 2 * tw, rng.randint(1, 4 * tw), rng.randint(1, 4 * tw)])
    h = rng.choice([0, th, 3 * th, rng.randint(1, 4 * th), rng.randint(1, 4 * th)])
    count = -(-w // tw) * -(-h // th)
    want, data_fmt = rng.randrange(FMTS), rng.randrange(FMTS)
    f = [i,
         1 if rng.random() < 0.3 else 0,                     # square
         tw, th,
         1 if rng.random() < 0.04 else 0,                    # qi_fail
         1 if rng.random() < 0.04 else 0,                    # find_fail
         rng.randrange(FMTS),                                # tex_fmt
         1 if rng.random() < 0.03 else 0,                    # pipe_null
         rng.choice([0x2c] * 30 + [0x2b, 0x30, 0]),          # desc_size
         0 if rng.random() < 0.03 else 1,                    # name_ok
         1 if rng.random() < 0.25 else 0,                    # use_source
         want, data_fmt, w, h,
         w * 4 + rng.randint(0, 9),                          # pitch
         rng.choice([count, rng.randint(1, max(1, count))]) if rng.random() < 0.25 else 0,  # fail_create_at (often the corner)
         rng.randint(1, max(1, count)) if rng.random() < 0.25 else 0,   # fail_set_at
         u32(-1) if rng.random() < 0.08 else 0,              # src_fmt_rc
         rng.randrange(FMTS),                                # src_fmt
         u32(-1) if rng.random() < 0.08 else 0,              # src_size_rc
         u32(-1) if rng.random() < 0.4 else 0,               # pix_rc1
         u32(-1) if rng.random() < 0.15 else 0,              # pix_rc2
         0 if rng.random() < 0.1 else 1,                     # draw_cb
         1 if rng.random() < 0.5 else 0, rand_float(rng),    # alpha
         1 if rng.random() < 0.4 else 0,                     # color
         rand_float(rng), rand_float(rng), rand_float(rng)]
    for _ in range(2):                                       # two draws
        f.append(1 if rng.random() < 0.25 else 0)
        f += [u32(v) for v in rect(rng, w, h, tw, th)]
        f += [u32(v) for v in dst_rect(rng)]
    same = rng.random() < 0.85
    f += [1 if rng.random() < 0.05 else 0,                   # sd_data_null
          1 if rng.random() < 0.05 else 0,                   # sd_fmt_null
          rng.randrange(FMTS),
          w if same else rng.randint(0, 4 * tw),
          h if same else rng.randint(0, 4 * th),
          w * 2 + rng.randint(0, 9),
          rng.randint(1, max(1, count)) if rng.random() < 0.25 else 0,  # sd_fail_at
          u32(rng.randint(-2, count + 2))]                   # tex_extra
    assert len(f) == 56
    return f


def main():
    rng = random.Random(0x5841)
    print("# generated by tests/ximage_cases.py; fields: enum in tests/test_ximage.c")
    for i in range(N_CASES):
        print(" ".join(str(v) for v in case(rng, i)))


if __name__ == "__main__":
    main()
